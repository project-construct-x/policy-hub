package org.constructx.policyhub.policies.api.dto;

import com.fasterxml.jackson.databind.JsonNode;
import com.jayway.jsonpath.internal.filter.LogicalOperator;
import io.swagger.v3.oas.annotations.media.Schema;
import org.constructx.policyhub.policies.domain.PolicyCategory;

import java.time.Instant;
import java.util.List;
import java.util.UUID;

@Schema(description = "Persisted Policy Hub policy")
public record PolicyResponse(

        @Schema(
                description = "Backend-generated technical identifier of the policy",
                example = "00000000-0000-0000-0000-000000000001"
        )
        UUID id,

        @Schema(
                description = "Unique business identifier defined by the client",
                example = "oeffentlicher-zugriff-projektdokumentation"
        )
        String policyId,

        @Schema(
                description = "Policy category",
                example = "ACCESS",
                allowableValues = {"ACCESS", "CONTRACT"}
        )
        PolicyCategory category,

    @Schema(
            description = """
                    Ordered list of structured policy constraints.
                    Supported types are MEMBERSHIP, DATE_RANGE and FRAMEWORK_AGREEMENT.
                    """,
            example = """
                    [
                      {
                        "type": "MEMBERSHIP",
                        "value": "active"
                      },
                      {
                        "type": "FRAMEWORK_AGREEMENT",
                        "agreement": "DataExchangeGovernance"
                      }
                    ]
                    """
    )
    List<JsonNode> constraints,

    @Schema(
            description = """
                    Logical combination of the constraints: AND (odrl:and) or OR (odrl:or).
                    """,
            example = "AND",
            allowableValues = {"AND", "OR"}
    )
    LogicalOperator logicalOperator,

    @Schema(
            description = """
                    German legal text generated by the frontend,
                    persisted and returned unchanged by the backend.
                    """,
            example = "Der Zugriff ist ausschließlich aktiven Mitgliedern gestattet."
    )
    String legalText,

        @Schema(
                description = "Creation timestamp in ISO-8601 format",
                example = "2026-03-15T10:30:00Z"
        )
        Instant createdAt,

        @Schema(
                description = "Timestamp of the most recent update in ISO-8601 format",
                example = "2026-04-29T09:40:00Z"
        )
        Instant updatedAt
) {
}