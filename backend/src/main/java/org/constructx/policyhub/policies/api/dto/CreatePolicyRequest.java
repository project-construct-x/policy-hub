package org.constructx.policyhub.policies.api.dto;

import com.fasterxml.jackson.databind.JsonNode;
import io.swagger.v3.oas.annotations.media.Schema;
import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Pattern;
import jakarta.validation.constraints.Size;
import org.constructx.policyhub.policies.domain.LogicalOperator;
import org.constructx.policyhub.policies.domain.PolicyCategory;
import org.constructx.policyhub.policies.domain.PolicyId;

import java.util.List;

public record CreatePolicyRequest(

        @Schema(
                description = "Unique business identifier. Must start with the fixed prefix con-x-ph-",
                example = "con-x-ph-zugriff-konsortium-mitglieder",
                minLength = 1,
                maxLength = 200
        )
        @NotBlank(message = "policyId must not be blank")
        @Size(max = 200, message = "policyId must not exceed 200 characters")
        @Pattern(regexp = PolicyId.PATTERN, message = "policyId must start with the prefix con-x-ph-")
        String policyId,

        @Schema(
                description = "Policy category",
                example = "ACCESS"
        )
        @NotNull(message = "category is required")
        PolicyCategory category,

        @Schema(
                description = """
                Ordered list of policy constraints. Supported types are
                MEMBERSHIP, DATE_RANGE and FRAMEWORK_AGREEMENT.
                DATE_RANGE defines a start and end date in ISO-8601 format.
                """,
                example = """
                [
                  {
                    "type": "MEMBERSHIP",
                    "value": "active"
                  },
                  {
                    "type": "DATE_RANGE",
                    "startDate": "2026-08-01",
                    "endDate": "2027-12-31"
                  }
                ]
                """
        )
        @NotNull(message = "constraints are required")
        List<JsonNode> constraints,

        @Schema(
                description = """
                Logical combination of the constraints: AND (all must be fulfilled,
                odrl:and) or OR (at least one must be fulfilled, odrl:or).
                Optional; defaults to AND if omitted.
                """,
                example = "AND",
                defaultValue = "AND",
                allowableValues = {"AND", "OR"},
                requiredMode = Schema.RequiredMode.NOT_REQUIRED
        )
        LogicalOperator logicalOperator,

        @Schema(
                description = """
                        German legal text generated by the frontend.
                        It is persisted and returned unchanged by the backend.
                        """,
                example = "Der Zugriff ist ausschließlich aktiven Mitgliedern gestattet.",
                minLength = 1
        )
        @NotBlank(message = "legalText must not be blank")
        String legalText
) {
}